#!/usr/bin/env pwsh
# Regenerate THIRD-PARTY-LICENSES.md from the crates that actually link into the
# Windows build. Run from anywhere; output goes to the repository root.
#
#   pwsh scripts/generate-third-party-licenses.ps1
#
# The installer ships the result next to NOTICE (see apps/illness/Packager.toml),
# because Apache-2.0, MIT, MPL-2.0 and BSL-1.0 all require the license text to
# travel with a binary distribution.
$ErrorActionPreference = 'Stop'

$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$outFile = Join-Path $root 'THIRD-PARTY-LICENSES.md'
$target = 'x86_64-pc-windows-msvc'

Push-Location $root
try {
    $meta = cargo metadata --format-version 1 --filter-platform $target 2>$null | ConvertFrom-Json
} finally {
    Pop-Location
}

$packages = @{}
foreach ($p in $meta.packages) { $packages[$p.id] = $p }

$workspace = @{}
foreach ($m in $meta.workspace_members) { $workspace[$m] = $true }

$registryRoot = (Get-ChildItem (Join-Path $env:USERPROFILE '.cargo\registry\src') -Directory |
    Select-Object -First 1).FullName

$rows = New-Object System.Collections.Generic.List[object]
$texts = [ordered]@{}

foreach ($node in $meta.resolve.nodes) {
    if ($workspace.ContainsKey($node.id)) { continue }
    $pkg = $packages[$node.id]
    if (-not $pkg) { continue }

    $crateDir = Join-Path $registryRoot ("{0}-{1}" -f $pkg.name, $pkg.version)
    $licenseFiles = @()
    if (Test-Path $crateDir) {
        $licenseFiles = Get-ChildItem $crateDir -File |
            Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING|NOTICE|UNLICENSE)' } |
            Sort-Object Name
    }

    $body = ''
    if ($licenseFiles.Count -gt 0) {
        foreach ($f in $licenseFiles) {
            $content = (Get-Content $f.FullName -Raw) -replace "`r`n", "`n"
            $normalized = ($content -replace '\s+', ' ').Trim()
            $sha = [System.Security.Cryptography.SHA256]::Create()
            $hash = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($normalized))
            $key = ([System.BitConverter]::ToString($hash) -replace '-', '').Substring(0, 8)
            if (-not $texts.Contains($key)) {
                $texts[$key] = "### License text: $($f.Name) (first seen in $($pkg.name) $($pkg.version))`n`n$($content.Trim())"
            }
            $body += "- ``$($f.Name)`` (text $key)`n"
        }
    } else {
        $body = "- No license file in the crate archive; see $($pkg.repository)`n"
    }

    $rows.Add([pscustomobject]@{
        Name       = $pkg.name
        Version    = $pkg.version
        License    = if ($pkg.license) { $pkg.license } else { 'see repository' }
        Repository = if ($pkg.repository) { $pkg.repository } else { '' }
        Files      = $body.TrimEnd()
    })
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Third-party licenses')
[void]$sb.AppendLine()
[void]$sb.AppendLine('Illness itself is licensed MIT OR Apache-2.0 (see `LICENSE-MIT`, `LICENSE-APACHE`,')
[void]$sb.AppendLine('and `NOTICE`). The crates below are linked into the Windows build for')
[void]$sb.AppendLine("``$target``; each entry names its declared license and the license files the")
[void]$sb.AppendLine('crate archive ships. Full texts follow the table, deduplicated.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('Generated by `scripts/generate-third-party-licenses.ps1`; do not edit by hand.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Crate | Version | License |')
[void]$sb.AppendLine('| --- | --- | --- |')
foreach ($r in $rows | Sort-Object Name) {
    $link = if ($r.Repository) { "[$($r.Name)]($($r.Repository))" } else { $r.Name }
    [void]$sb.AppendLine("| $link | $($r.Version) | $($r.License) |")
}

[void]$sb.AppendLine()
[void]$sb.AppendLine('## Per-crate license files')
[void]$sb.AppendLine()
foreach ($r in $rows | Sort-Object Name) {
    [void]$sb.AppendLine("### $($r.Name) $($r.Version) — $($r.License)")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine($r.Files)
    [void]$sb.AppendLine()
}

[void]$sb.AppendLine('## License texts')
[void]$sb.AppendLine()
foreach ($k in $texts.Keys) {
    [void]$sb.AppendLine($texts[$k])
    [void]$sb.AppendLine()
}

Set-Content -Path $outFile -Value $sb.ToString() -NoNewline -Encoding utf8
"{0} crates, {1} unique license texts -> {2} ({3:N0} bytes)" -f $rows.Count, $texts.Count, $outFile, (Get-Item $outFile).Length
